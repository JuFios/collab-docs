import { CONTENT_FIELD, LINK_PROTOCOLS, LINK_REL, NODE_SPECS } from '@collab-docs/shared/content';
import type { Attribute, Extensions } from '@tiptap/core';
import Collaboration, { isChangeOrigin } from '@tiptap/extension-collaboration';
import CollaborationCaret from '@tiptap/extension-collaboration-caret';
import { OrderedList, TaskItem, TaskList } from '@tiptap/extension-list';
import Mention from '@tiptap/extension-mention';
import UniqueID from '@tiptap/extension-unique-id';
import { Placeholder } from '@tiptap/extensions';
import StarterKit from '@tiptap/starter-kit';
import type { WebsocketProvider } from 'y-websocket';
import type * as Y from 'yjs';
import { renderCaret, renderSelection } from './caret';
import { CodeBlockWithLanguage } from './code-block-extension';
import { ImageBlock } from './image-extension';
import { SlashCommand } from './slash-command';

export interface EditorExtensionOptions {
  ydoc: Y.Doc;
  provider: WebsocketProvider;
  /** Omitted where images cannot be uploaded (guests): the slash menu then has no Image entry. */
  pickImage?: () => void;
  /**
   * Whether this client may change the document. A reader must not let the editor write block ids into its
   * local copy: the server ignores a reader's updates, and the copy would stay "unsaved" for good.
   */
  editable: boolean;
}

/** Block types that carry a stable `id` (comment anchors); taken from the content model, not repeated here. */
const BLOCK_ID_TYPES = Object.entries(NODE_SPECS)
  .filter(([, spec]) => 'id' in spec.attrs)
  .map(([name]) => name);

const keepOnly = (attributes: unknown, names: readonly string[]): Record<string, Attribute> =>
  Object.fromEntries(
    Object.entries((attributes ?? {}) as Record<string, Attribute>).filter(([name]) =>
      names.includes(name),
    ),
  );

/** `OrderedList` also keeps a list style `type` (a, i, ...) that the content model does not have. */
const OrderedListFromOne = OrderedList.extend({
  addAttributes() {
    return keepOnly(this.parent?.(), ['start']);
  },
});

/** `Mention` also records the trigger character; the content model has only the user id and the label. */
const MentionNode = Mention.extend({
  addAttributes() {
    return keepOnly(this.parent?.(), ['id', 'label']);
  },
});

/**
 * The editor schema. It is the content model of `@collab-docs/shared/content` expressed as Tiptap extensions:
 * the sanitiser removes anything outside that model, so the editor must not offer anything outside it either
 * (no strike, underline, quote or rule, which StarterKit enables by default). `editor-extensions.test.ts` builds
 * an editor from this list and compares its schema with the model.
 */
export function createEditorExtensions({
  ydoc,
  provider,
  pickImage,
  editable,
}: EditorExtensionOptions): Extensions {
  return [
    StarterKit.configure({
      // history comes from the Yjs UndoManager (Collaboration), which only undoes this user's own changes
      undoRedo: false,
      heading: { levels: [1, 2, 3] },
      codeBlock: false,
      orderedList: false,
      blockquote: false,
      horizontalRule: false,
      strike: false,
      underline: false,
      link: {
        openOnClick: false,
        protocols: LINK_PROTOCOLS.map((protocol) => protocol.replace(':', '')),
        HTMLAttributes: { rel: LINK_REL, target: '_blank' },
      },
    }),
    CodeBlockWithLanguage,
    OrderedListFromOne,
    TaskList,
    TaskItem.configure({ nested: true }),
    ImageBlock,
    // rendered in the document; there is no suggestion UI for mentions yet
    MentionNode.configure({ suggestions: [] }),
    UniqueID.configure({
      attributeName: 'id',
      types: BLOCK_ID_TYPES,
      updateDocument: editable,
      // ids that arrive through Yjs were generated by another client; rewriting them would make clients fight
      filterTransaction: (transaction) => !isChangeOrigin(transaction),
    }),
    Placeholder.configure({ placeholder: 'Type “/” for blocks' }),
    SlashCommand.configure({ pickImage }),
    Collaboration.configure({ document: ydoc, field: CONTENT_FIELD }),
    CollaborationCaret.configure({
      provider,
      // the server replaces `user` with the authenticated identity before it reaches anyone else
      user: { name: '', color: '' },
      render: renderCaret,
      selectionRender: renderSelection,
    }),
  ];
}
